    ax.set_ylabel('Flapwise (m)', fontsize=10)
    ax.set_zlabel('Radial (m)', fontsize=10)
    ax.set_title(f'Blade Geometry (R={blade.R:.2f}m, Hub={blade.hub_radius:.2f}m)', fontsize=12)
    ax.set_box_aspect((1, 0.5, 2.5))
    ax.legend(loc='best', fontsize=9)
    ax.grid(True, alpha=0.2)

